    const navMenu = document.getElementById('nav-menu');

    function syncMenuLabel() {
        if (!menuToggle) return;
        const open = menuToggle.getAttribute('aria-expanded') === 'true';
        menuToggle.setAttribute('aria-label', t(open ? 'a11y.closeMenu' : 'a11y.openMenu'));
        menuToggle.querySelector('path').setAttribute('d', open ? 'M6 18L18 6M6 6l12 12' : 'M4 6h16M4 12h16M4 18h16');
    }
    function setMenu(open) {
        if (!menuToggle || !navMenu) return;
        menuToggle.setAttribute('aria-expanded', String(open));
        navMenu.classList.toggle('is-open', open);
        syncMenuLabel();
    }
    if (menuToggle && navMenu) {
        menuToggle.addEventListener('click', () => setMenu(menuToggle.getAttribute('aria-expanded') !== 'true'));
        navMenu.addEventListener('click', e => { if (e.target.closest('a')) setMenu(false); });
        document.addEventListener('keydown', e => {
            if (e.key === 'Escape' && navMenu.classList.contains('is-open')) { setMenu(false); menuToggle.focus(); }
        });
    }

